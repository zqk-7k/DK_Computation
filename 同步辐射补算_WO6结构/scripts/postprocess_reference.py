#!/usr/bin/env python3
"""Export an actual FEFF W L3 reference calculation to TXT and figures.

No experimental spectrum or numerical mock output is generated by this script.
Input xmu.dat and chi.dat must come from the same finite-POM profile.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def numeric_table(path, minimum_columns):
    rows = []
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip() or line.lstrip().startswith(("#", "*", "!")):
            continue
        try:
            values = [float(s.replace("D", "E").replace("d", "e")) for s in line.split()]
        except ValueError:
            if rows:
                raise ValueError(f"Text after numerical rows in {path}")
            continue
        rows.append(values)
    if len(rows) < 8 or len({len(r) for r in rows}) != 1:
        raise ValueError(f"Incomplete or inconsistent native table: {path}")
    data = np.asarray(rows)
    if data.shape[1] < minimum_columns or not np.isfinite(data).all():
        raise ValueError(f"Nonfinite or insufficient columns: {path}")
    if not (np.diff(data[:, 0]) > 0).all():
        raise ValueError(f"Native axis is not strictly increasing: {path}")
    return data


def save_txt(path, columns, array):
    np.savetxt(path, array, delimiter="\t", fmt="%.10g",
               header="Finite alpha-PW12O40 crystallographic geometry; theoretical FEFF reference.\n"
               + "\t".join(columns))


def validate_pair(xanes_path, exafs_path):
    """Reject stale, mixed-model, mixed-profile, incomplete or untracked inputs."""
    records = []
    for path, mode, name in [(xanes_path, "xanes", "xmu.dat"), (exafs_path, "exafs", "chi.dat")]:
        path = Path(path).resolve()
        if path.name != name:
            raise ValueError(f"Expected native {name}, not {path.name}")
        directory = path.parent
        job = json.loads((directory/"job.json").read_text(encoding="utf-8"))
        result = json.loads((directory/"run_result.json").read_text(encoding="utf-8"))
        if job["mode"] != mode or result.get("mode") != mode or result.get("status") != "complete":
            raise ValueError("Both modes need successful, matching FEFF completion records")
        if job.get("edge") != "W_L3" or job.get("atom_count") != 53 or job.get("finite_molecule") is not True or job.get("periodic_images_added") != 0:
            raise ValueError("Inputs do not describe the finite 53-atom W L3 reference")
        if directory != (ROOT/job["path"]).resolve():
            raise ValueError("Job path disagrees with package manifest")
        source = (ROOT/job["source_xyz"]).resolve()
        if source != (ROOT/"references/alpha_PW12O40_crystallographic.xyz").resolve():
            raise ValueError("Unexpected reference structure")
        if digest(source) != job["source_sha256"] or result.get("source_sha256") != job["source_sha256"]:
            raise ValueError("Reference structure hash mismatch")
        if digest(ROOT/"references/reference_model_manifest.json") != job["source_metadata_sha256"]:
            raise ValueError("Reference metadata changed after calculation")
        actual_input = digest(directory/"feff.inp")
        if actual_input != job["feff_input_sha256"] or actual_input != result.get("input_sha256"):
            raise ValueError("FEFF input changed after calculation")
        files = result.get("validation", {}).get("files", [])
        scf = result.get("validation", {}).get("scf_convergence", {})
        if scf.get("status") != "confirmed" or not scf.get("evidence"):
            raise ValueError("FEFF self-consistency convergence has not been confirmed")
        for record in files:
            recorded_path = directory/record["name"]
            if recorded_path.parent != directory or not recorded_path.is_file() or digest(recorded_path) != record["sha256"]:
                raise ValueError("Native output is untracked or changed after FEFF completion")
        recorded = next((f for f in files if f.get("name") == name), None)
        if not recorded or recorded["sha256"] != digest(path):
            raise ValueError("Native output is untracked or changed after FEFF completion")
        records.append({"job":job,"completion_sha256":digest(directory/"run_result.json")})
    fields = ("profile","source_sha256","source_metadata_sha256","absorber_source_index","scf_radius_A")
    if any(records[0]["job"][f] != records[1]["job"][f] for f in fields):
        raise ValueError("XANES/EXAFS are from different profiles or structures")
    return records


def process(xanes_path, exafs_path, output):
    from larch import Group
    from larch.xafs import xftf, cauchy_wavelet
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib import font_manager
    xanes_path, exafs_path, output = map(Path, (xanes_path, exafs_path, output))
    if output.exists():
        raise FileExistsError("Use a new output directory to preserve earlier exports")
    completion_records = validate_pair(xanes_path, exafs_path)
    xm, ch = numeric_table(xanes_path, 6), numeric_table(exafs_path, 2)
    if xm[0, 0] > 10100 or xm[-1, 0] < 10300:
        raise ValueError("Native xmu.dat does not cover 10100-10300 eV. Rerun FEFF; no extrapolation or curve shifting is allowed.")
    if ch[0, 0] < -0.002 or ch[0, 0] > 0.002 or ch[-1, 0] < 12.0:
        raise ValueError("chi.dat must start at k~0 and extend beyond 12 inverse angstrom")
    # FEFF normally includes k=0. A <=0.002 rounding mismatch is recorded below.
    kstep = 0.05
    k = np.arange(int(np.floor(ch[-1, 0]/kstep)) + 1)*kstep
    if len(k) >= 1024:
        raise ValueError("Input too long for the specified 2048-point WT")
    chi = np.interp(k, ch[:, 0], ch[:, 1])
    transforms = {}
    for weight in (1, 2, 3):
        g = Group()
        xftf(k, chi, group=g, kmin=3, kmax=12, kweight=weight, dk=1, dk2=1,
             window="hanning", nfft=2048, kstep=kstep, rmax_out=6)
        transforms[weight] = (np.asarray(g.r), np.asarray(g.chir), np.asarray(g.kwin))
    wt = Group()
    cauchy_wavelet(k, chi, group=wt, kweight=2, rmax_out=6, nfft=2048)
    rwt, wcomplex = np.asarray(wt.wcauchy_r), np.asarray(wt.wcauchy)
    if wcomplex.shape != (len(rwt), len(k)):
        raise ValueError("Unexpected Larch wavelet dimensions")
    output.mkdir(parents=True)
    txt, figs = output/"txt", output/"figures"
    txt.mkdir(); figs.mkdir()
    save_txt(txt/"W_L3_xmu_native.txt", ["energy_eV", "relative_energy_eV", "k_A^-1", "mu_FEFF", "mu0_FEFF", "native_scaled_chi"] + [f"extra_{j}" for j in range(6, xm.shape[1])], xm)
    save_txt(txt/"W_L3_chi_native.txt", ["k_A^-1", "chi"] + [f"extra_{j}" for j in range(2, ch.shape[1])], ch)
    save_txt(txt/"W_L3_chi_common_grid.txt", ["k_A^-1", "chi", "k_chi", "k2_chi", "k3_chi"], np.column_stack([k, chi, k*chi, k**2*chi, k**3*chi]))
    for weight, (r, complex_ft, window) in transforms.items():
        save_txt(txt/f"W_L3_FT_k{weight}.txt", ["R_uncorrected_A", "real_FT", "imag_FT", "abs_FT"], np.column_stack([r, complex_ft.real, complex_ft.imag, np.abs(complex_ft)]))
        save_txt(txt/f"W_L3_FT_k{weight}_window.txt", ["k_A^-1", "window"], np.column_stack([k, window]))
    rk, rr = np.meshgrid(k, rwt)
    save_txt(txt/"W_L3_WT_k2_long.txt", ["k_A^-1", "R_A", "real_WT", "imag_WT", "abs_WT"], np.column_stack([rk.ravel(), rr.ravel(), wcomplex.real.ravel(), wcomplex.imag.ravel(), np.abs(wcomplex).ravel()]))
    try:
        font_manager.findfont("Arial", fallback_to_default=False)
        font = "Arial"
    except ValueError:
        font = "DejaVu Sans"
    plt.rcParams.update({"font.family": font, "font.size": 8, "axes.linewidth": .5,
        "lines.linewidth": .5, "xtick.major.width": .5, "ytick.major.width": .5,
        "pdf.fonttype": 42, "svg.fonttype": "none"})
    fig, axs = plt.subplots(2, 2, figsize=(7.1, 5.1))
    axs[0, 0].plot(xm[:, 0], xm[:, 3], color="black")
    axs[0, 0].set(xlim=(10100, 10300), xlabel="Photon energy (eV)", ylabel="Calculated absorption (FEFF units)")
    axs[0, 1].plot(k, k**3*chi, color="black")
    axs[0, 1].set(xlim=(3, 12), xlabel=r"$k$ ($\AA^{-1}$)", ylabel=r"$k^3\chi(k)$ ($\AA^{-3}$)")
    r, ft, _ = transforms[3]
    axs[1, 0].plot(r, np.abs(ft), color="black")
    axs[1, 0].set(xlim=(0, 6), xlabel=r"$R$ ($\AA$, no phase correction)", ylabel=r"$|\chi(R)|$ (FT units)")
    im = axs[1, 1].pcolormesh(k, rwt, np.abs(wcomplex), cmap="viridis", shading="auto", rasterized=True)
    axs[1, 1].set(xlim=(3, 12), ylim=(0, 6), xlabel=r"$k$ ($\AA^{-1}$)", ylabel=r"$R$ ($\AA$)")
    fig.colorbar(im, ax=axs[1, 1], label=r"$|\mathrm{WT}[k^2\chi(k)]|$")
    for i, ax in enumerate(axs.flat):
        ax.text(-.18, 1.07, "abcd"[i], transform=ax.transAxes, fontweight="bold", fontsize=10)
    fig.subplots_adjust(left=.12, right=.97, bottom=.13, top=.93, hspace=.43, wspace=.5)
    fig.text(.5, .025, "Finite phosphotungstate reference: calculated spectra, not a supported single-W catalyst", ha="center", fontsize=7)
    for ext in ("png", "pdf", "svg", "tiff"):
        fig.savefig(figs/f"W_L3_reference.{ext}", dpi=400)
    plt.close(fig)
    provenance = {"status": "postprocessed", "reference_only": True,
        "xmu_sha256": digest(xanes_path), "chi_sha256": digest(exafs_path),
        "native_energy_eV": [float(xm[0,0]), float(xm[-1,0])],
        "native_k_A_inv": [float(ch[0,0]), float(ch[-1,0])],
        "k0_endpoint_clamp_A_inv": max(0.0, float(ch[0,0])),
        "phase_correction": False, "energy_shifts": [],
        "FT": {"kmin":3,"kmax":12,"kweights":[1,2,3],"dk":1,"window":"hanning","nfft":2048},
        "WT": {"method":"Larch Cauchy","kweight":2,"nfft":2048},
        "font":font,"notes":"No charge calibration, potential assignment, experimental fit or active-site conclusion."}
    provenance["completion_records"] = completion_records
    (output/"provenance.json").write_text(json.dumps(provenance, indent=2)+"\n", encoding="utf-8")
    return output


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--xanes", required=True, type=Path)
    p.add_argument("--exafs", required=True, type=Path)
    p.add_argument("--output", required=True, type=Path)
    args = p.parse_args()
    print(process(args.xanes, args.exafs, args.output))
